-- Scans of a video link shared into the app (TikTok for now): the AI reads the
-- post's caption and turns it into a workout or a meal.
--
-- LinkScans is the allowance ledger - one row per scan, timestamps and kind
-- only, like FoodScans. Paid tiers get a per-kind daily allowance; a Free
-- account gets a small lifetime trial, counted from the rows marked IsTrial so
-- scans made while subscribed never eat into it.
CREATE TABLE dbo.linkscans (
    linkscanid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    userid uuid NOT NULL,
    kind varchar(10) NOT NULL,
    istrial boolean DEFAULT false NOT NULL,
    scannedatutc timestamp(3) DEFAULT dbo.sysutcdatetime() NOT NULL,
    CONSTRAINT pk_linkscans PRIMARY KEY (linkscanid),
    CONSTRAINT ck_linkscans_kind CHECK (kind IN ('workout', 'meal')),
    CONSTRAINT fk_linkscans_users FOREIGN KEY (userid) REFERENCES dbo.users (userid) ON DELETE CASCADE
);

CREATE INDEX ix_linkscans_user ON dbo.linkscans (userid, scannedatutc);

-- The AI's reading of a public post, shared by everyone who imports the same
-- video: a viral recipe is paid for once. Keyed by the provider's own video id.
-- Holds only what the post itself says publicly - nothing about who imported it.
CREATE TABLE dbo.linkscancache (
    provider varchar(20) NOT NULL,
    videoid varchar(64) NOT NULL,
    resultjson text NOT NULL,
    createdatutc timestamp(3) DEFAULT dbo.sysutcdatetime() NOT NULL,
    CONSTRAINT pk_linkscancache PRIMARY KEY (provider, videoid)
);
