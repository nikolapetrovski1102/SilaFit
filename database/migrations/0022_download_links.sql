-- Tagged download links: https://sila.fitness/download?src=<code>, one per
-- partner gym / shop / creator QR code and per social profile. Every open of the
-- page is a row in DownloadVisits; when the app is installed and makes its first
-- device login, the newest unmatched phone visit from the same network inside
-- the attribution window is claimed for that new account (MatchedUserId). From
-- there the admin report follows the lead on to sign-up and purchase.
--
-- DownloadSources is the allow-list: a ?src= that isn't here is recorded as an
-- untagged (direct) visit, so nobody can fill the report with made-up sources.
CREATE TABLE dbo.downloadsources (
    code varchar(40) COLLATE ci NOT NULL,
    label varchar(100) NOT NULL,
    channel varchar(20) NOT NULL,
    sortorder integer DEFAULT 0 NOT NULL,
    isactive boolean DEFAULT true NOT NULL,
    createdatutc timestamp(3) DEFAULT dbo.sysutcdatetime() NOT NULL,
    CONSTRAINT pk_downloadsources PRIMARY KEY (code),
    CONSTRAINT ck_downloadsources_channel CHECK (channel IN ('partner', 'social'))
);

-- VisitorId is a random id the page keeps in the browser, so a phone that opens
-- the link three times counts as one device. IpHash is an HMAC of the visitor's
-- network address (never the address itself), kept only as long as it can still
-- be matched to an install and wiped after that (see usp_download_recordvisit).
CREATE TABLE dbo.downloadvisits (
    visitid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sourcecode varchar(40) COLLATE ci,
    visitorid uuid,
    platform varchar(10) NOT NULL,
    devicelabel varchar(60),
    iphash bytea,
    visitedatutc timestamp(3) DEFAULT dbo.sysutcdatetime() NOT NULL,
    matcheduserid uuid,
    matchedatutc timestamp(3),
    CONSTRAINT pk_downloadvisits PRIMARY KEY (visitid),
    CONSTRAINT ck_downloadvisits_platform CHECK (platform IN ('ios', 'android', 'desktop')),
    CONSTRAINT fk_downloadvisits_sources FOREIGN KEY (sourcecode) REFERENCES dbo.downloadsources (code) ON DELETE SET NULL,
    CONSTRAINT fk_downloadvisits_users FOREIGN KEY (matcheduserid) REFERENCES dbo.users (userid) ON DELETE SET NULL
);

CREATE INDEX ix_downloadvisits_source ON dbo.downloadvisits (sourcecode, visitedatutc);
CREATE INDEX ix_downloadvisits_unmatched ON dbo.downloadvisits (iphash, visitedatutc)
    WHERE iphash IS NOT NULL AND matcheduserid IS NULL;
-- An install is credited to one visit at most.
CREATE UNIQUE INDEX uq_downloadvisits_matcheduser ON dbo.downloadvisits (matcheduserid)
    WHERE matcheduserid IS NOT NULL;

