-- Catalog exercise clean-up: equipment types and form images.
--
-- The active-workout tracker shows bar-and-plate math and starts a fresh set at
-- the 20 kg bar only for Barbell exercises, and the exercise recommender uses the
-- same column to keep barbell/machine work away from people without that kit.
-- Close to half the imported catalog had no EquipmentType at all (Air Squat,
-- Bench Press, Lat Raise, ...), and a handful were tagged wrong (Goblet Squat and
-- Lateral Raise as Barbell, the band pulldowns as Cable). This gives every system
-- exercise the equipment it is actually done with; movements that need nothing
-- (cardio, mobility, core, the circuit placeholders) are Bodyweight, and loads
-- that are neither a weight nor a machine (medicine ball, sled, foam roller) are
-- Other.
--
-- Rows are matched on name and on the equipment they were imported with, so an
-- exercise an admin has re-tagged since is left alone.
--
-- It also clears DemoVideoUrl where it holds a still image: the free-exercise-db
-- step photos were the only "demos" in the catalog, and the app now only offers
-- a video in-app and otherwise searches the web for the exercise's form.

